package com.time.coworking.util;

import com.itextpdf.kernel.colors.ColorConstants;
import com.itextpdf.kernel.colors.DeviceRgb;
import com.itextpdf.kernel.pdf.PdfDocument;
import com.itextpdf.kernel.pdf.PdfWriter;
import com.itextpdf.layout.Document;
import com.itextpdf.layout.borders.Border;
import com.itextpdf.layout.element.Cell;
import com.itextpdf.layout.element.Paragraph;
import com.itextpdf.layout.element.Table;
import com.itextpdf.layout.properties.TextAlignment;
import com.itextpdf.layout.properties.UnitValue;
import com.time.coworking.dto.ReportRow;

import java.io.File;
import java.io.IOException;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;

/**
 * Exports any report (list of ReportRow) to a styled PDF.
 * Handles arbitrary column counts by dividing A4 width evenly.
 */
public final class ReportPdfExporter {

    private static final DeviceRgb BRAND_DARK  = new DeviceRgb(2, 44, 34);
    private static final DeviceRgb BRAND_MID   = new DeviceRgb(6, 95, 70);
    private static final DeviceRgb BRAND_LIGHT = new DeviceRgb(13, 148, 136);
    private static final DeviceRgb STRIPE      = new DeviceRgb(240, 253, 250);
    private static final DeviceRgb LINE        = new DeviceRgb(226, 232, 240);
    private static final DeviceRgb INK         = new DeviceRgb(15, 23, 42);
    private static final DeviceRgb MUTED       = new DeviceRgb(100, 116, 139);

    private ReportPdfExporter() {}

    /**
     * @param title       report title, e.g. "Daily Booking Report"
     * @param subtitle    subtitle line, e.g. "2026-10-01 → 2026-10-26"
     * @param rows        rows to render
     * @param outFile     destination file
     */
    public static File export(String title, String subtitle,
                              List<ReportRow> rows, File outFile) throws IOException {

        try (PdfWriter writer = new PdfWriter(outFile);
             PdfDocument pdf = new PdfDocument(writer);
             Document doc = new Document(pdf)) {

            doc.setMargins(36, 36, 36, 36);

            // ── Header banner ──
            Table banner = new Table(UnitValue.createPercentArray(new float[]{1}))
                    .useAllAvailableWidth();
            Cell bannerCell = new Cell()
                    .setBackgroundColor(BRAND_DARK)
                    .setPadding(18)
                    .setBorder(Border.NO_BORDER);
            bannerCell.add(new Paragraph("TIME Co-working")
                    .setBold().setFontSize(20).setFontColor(ColorConstants.WHITE));
            bannerCell.add(new Paragraph("Management & Booking System")
                    .setFontSize(9).setFontColor(new DeviceRgb(200, 215, 210)));
            banner.addCell(bannerCell);
            doc.add(banner);
            doc.add(new Paragraph("\n"));

            // ── Report title ──
            doc.add(new Paragraph(title)
                    .setBold().setFontSize(18).setFontColor(BRAND_DARK));
            if (subtitle != null && !subtitle.isBlank()) {
                doc.add(new Paragraph(subtitle)
                        .setFontSize(11).setFontColor(MUTED));
            }
            doc.add(new Paragraph("\n"));

            // ── Rows ──
            if (rows == null || rows.isEmpty()) {
                doc.add(new Paragraph("No data for this report.")
                        .setItalic().setFontColor(MUTED));
            } else {
                List<String> columns = new ArrayList<>(rows.get(0).values().keySet());
                int n = columns.size();
                float[] widths = new float[n];
                for (int i = 0; i < n; i++) widths[i] = 1f;

                Table table = new Table(UnitValue.createPercentArray(widths))
                        .useAllAvailableWidth();

                // Header
                for (String col : columns) {
                    table.addHeaderCell(headerCell(prettyHeader(col)));
                }

                // Body
                boolean stripe = false;
                for (ReportRow row : rows) {
                    for (String col : columns) {
                        Object v = row.values().get(col);
                        String text = v == null ? "" : v.toString();
                        table.addCell(bodyCell(text, stripe));
                    }
                    stripe = !stripe;
                }

                doc.add(table);
            }

            // ── Footer ──
            doc.add(new Paragraph("\n"));
            doc.add(new Paragraph("Generated by TIME Co-working — " + java.time.LocalDate.now())
                    .setFontSize(9).setFontColor(MUTED)
                    .setTextAlignment(TextAlignment.CENTER));

            return outFile;
        }
    }

    private static Cell headerCell(String text) {
        return new Cell()
                .add(new Paragraph(text)
                        .setBold().setFontSize(9.5f).setFontColor(ColorConstants.WHITE))
                .setBackgroundColor(BRAND_LIGHT)
                .setPadding(7)
                .setBorder(new com.itextpdf.layout.borders.SolidBorder(LINE, 0.5f));
    }

    private static Cell bodyCell(String text, boolean stripe) {
        Cell c = new Cell()
                .add(new Paragraph(text == null ? "" : text)
                        .setFontSize(9).setFontColor(INK))
                .setPadding(6)
                .setBorder(new com.itextpdf.layout.borders.SolidBorder(LINE, 0.5f));
        if (stripe) c.setBackgroundColor(STRIPE);
        return c;
    }

    private static String prettyHeader(String raw) {
        StringBuilder sb = new StringBuilder();
        boolean cap = true;
        for (char c : raw.toCharArray()) {
            if (c == '_') { sb.append(' '); cap = true; }
            else if (cap) { sb.append(Character.toUpperCase(c)); cap = false; }
            else sb.append(c);
        }
        return sb.toString();
    }
}